const unsigned char *font_glyph(char c) {
    static const unsigned char box[7] = {0x1F,0x11,0x11,0x11,0x11,0x11,0x1F};
    unsigned char uc = (unsigned char)c;
    if (uc < ' ' || uc > '~') return box;
    const unsigned char *g = G[c - ' '];
    for (int i = 0; i < 7; ++i) if (g[i]) return g;
    return box; /* 未收录 ASCII 也显示方块 */
}
